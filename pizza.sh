#!/usr/bin/env bash
# pizza-hacking — self-hosted OWASP Juice Shop CTF.
#
#   ./pizza.sh up [--players N]   start (first run generates every credential)
#   ./pizza.sh creds              print the logins again
#   ./pizza.sh status             docker compose ps
#   ./pizza.sh logs [service]     follow logs
#   ./pizza.sh reset-juice        recreate every Juice Shop (fresh state)
#   ./pizza.sh down [--wipe]      stop; --wipe also deletes CTFd data, .env, certs
#   ./pizza.sh test               run the end-to-end test suite in an isolated stack
#
# Only bash and docker (with the compose plugin) are needed on the host; every
# helper runs in a container. Settings for the first run can be passed as
# environment variables: DOMAIN, HTTP_PORT (or "off"), HTTPS_PORT, PUBLIC_PORT,
# CTF_NAME, JUICE_THEME. PIZZA_COMPOSE_OVERRIDE=/path/file.yml adds your own compose file.
set -euo pipefail

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
STATE_DIR="${PIZZA_STATE_DIR:-$REPO_DIR}"
PROJECT="${PIZZA_PROJECT:-pizza-hacking}"
ENV_FILE="$STATE_DIR/.env"
GEN_DIR="$STATE_DIR/generated"
CERT_DIR="$STATE_DIR/certs"

JUICE_IMAGE="bkimminich/juice-shop:v20.3.0"
TINYAUTH_IMAGE="ghcr.io/tinyauthapp/tinyauth:v5.2.0"
TOOLS_IMAGE="python:3.12-slim"
ADMIN_USER="admin"

die() { echo "pizza: $*" >&2; exit 1; }
info() { echo "==> $*"; }

# Letters and digits only: safe in .env, YAML, URLs and shell.
rand() {
  local out
  out="$(LC_ALL=C tr -dc 'A-Za-z0-9' </dev/urandom | head -c "${1:-24}" || true)"
  printf '%s' "$out"
}

env_get() {
  [[ -f "$ENV_FILE" ]] || return 0
  sed -n "s/^$1=//p" "$ENV_FILE" | tail -n1
}

# Add KEY=VALUE only if KEY is missing: nothing in .env is ever rotated.
env_default() {
  if [[ -z "$(env_get "$1")" ]]; then
    printf '%s=%s\n' "$1" "$2" >>"$ENV_FILE"
  fi
}

env_put() {
  local tmp
  tmp="$(mktemp "$ENV_FILE.XXXXXX")"
  grep -v "^$1=" "$ENV_FILE" >"$tmp" || true
  printf '%s=%s\n' "$1" "$2" >>"$tmp"
  chmod 600 "$tmp"
  mv "$tmp" "$ENV_FILE"
}

compose() {
  local files=(-f "$REPO_DIR/docker-compose.yml")
  [[ -f "$GEN_DIR/docker-compose.players.yml" ]] && files+=(-f "$GEN_DIR/docker-compose.players.yml")
  # Site-specific additions (labels, extra networks, ...), applied last.
  if [[ -n "${PIZZA_COMPOSE_OVERRIDE:-}" ]]; then
    [[ -f "$PIZZA_COMPOSE_OVERRIDE" ]] || die "PIZZA_COMPOSE_OVERRIDE: no such file: $PIZZA_COMPOSE_OVERRIDE"
    files+=(-f "$PIZZA_COMPOSE_OVERRIDE")
  fi
  PIZZA_STATE_DIR="$STATE_DIR" docker compose -p "$PROJECT" --project-directory "$REPO_DIR" \
    --env-file "$ENV_FILE" "${files[@]}" "$@"
}

# One-shot helper container. Output comes back on stdout, so generated files
# are always owned by the invoking user (rootful docker and rootless alike).
run_tool() {
  docker run --rm -i --pids-limit 256 --network none "$@"
}

check_prereqs() {
  command -v docker >/dev/null || die "docker is not installed"
  docker compose version >/dev/null 2>&1 || die "the docker compose plugin is missing"
  docker info >/dev/null 2>&1 || die "cannot talk to the docker daemon (permissions? is it running?)"
}

FIRST_RUN=0
init_env() {
  if [[ ! -f "$ENV_FILE" ]]; then
    FIRST_RUN=1
    mkdir -p "$STATE_DIR"
    umask 077
    cat >"$ENV_FILE" <<EOF
# pizza-hacking — generated by ./pizza.sh on $(date -u +%Y-%m-%dT%H:%MZ).
# Keep this file: it is the only copy of every password below.
# Values are generated once and never rotated; delete a line to regenerate it.
EOF
    umask 022
  fi

  env_default DOMAIN "${DOMAIN:-127.0.0.1.nip.io}"
  env_default HTTP_PORT "${HTTP_PORT:-80}"
  env_default HTTPS_PORT "${HTTPS_PORT:-443}"
  # The port players type in their browser. Differs from HTTPS_PORT only when
  # another reverse proxy in front of this stack terminates TLS.
  env_default PUBLIC_PORT "${PUBLIC_PORT:-$(env_get HTTPS_PORT)}"
  env_default CTF_NAME "${CTF_NAME:-Pizza Hacking}"
  # Juice Shop's CTF mode defaults to the black neon-fire theme; this one is light.
  env_default JUICE_THEME "${JUICE_THEME:-deeporange-indigo}"
  env_default PLAYERS 1

  # tinyauth (IdP) administrator — sees every player instance and CTFd.
  env_default TINYAUTH_ADMIN_USER "$ADMIN_USER"
  env_default TINYAUTH_ADMIN_PASSWORD "$(rand 20)"

  # CTFd administrator — a different account from the IdP admin.
  env_default CTFD_ADMIN_USER "ctfadmin"
  env_default CTFD_ADMIN_EMAIL "ctfadmin@pizza.invalid"
  env_default CTFD_ADMIN_PASSWORD "$(rand 20)"

  # Flag codes are HMAC-SHA1(CTF_KEY, challenge name). Rotating CTF_KEY
  # invalidates every flag already imported into CTFd.
  env_default CTF_KEY "$(rand 40)"
  env_default CTFD_SECRET_KEY "$(rand 48)"
  env_default CTFD_DB_PASSWORD "$(rand 32)"
  env_default CTFD_DB_ROOT_PASSWORD "$(rand 32)"
  chmod 600 "$ENV_FILE"
}

ensure_players() {
  local n="$1" i
  for ((i = 1; i <= n; i++)); do
    env_default "PLAYER${i}_PASSWORD" "$(rand 12)"
  done
  env_put PLAYERS "$n"
}

load_env() {
  DOMAIN="$(env_get DOMAIN)"
  HTTP_PORT="$(env_get HTTP_PORT)"
  HTTPS_PORT="$(env_get HTTPS_PORT)"
  PUBLIC_PORT="$(env_get PUBLIC_PORT)"
  PUBLIC_PORT="${PUBLIC_PORT:-$HTTPS_PORT}"
  PLAYERS="$(env_get PLAYERS)"
  PORT_SUFFIX=""
  [[ "$PUBLIC_PORT" == "443" ]] || PORT_SUFFIX=":$PUBLIC_PORT"
  env_put PORT_SUFFIX "$PORT_SUFFIX"
  [[ "$DOMAIN" =~ ^[a-z0-9]([a-z0-9.-]*[a-z0-9])?$ ]] || die "DOMAIN '$DOMAIN' is not a valid lowercase hostname"
  [[ "$HTTPS_PORT" =~ ^[0-9]+$ && "$PUBLIC_PORT" =~ ^[0-9]+$ ]] || die "HTTPS_PORT and PUBLIC_PORT must be port numbers"
  [[ "$HTTP_PORT" =~ ^[0-9]+$ || "$HTTP_PORT" == "off" ]] || die "HTTP_PORT must be a port number or 'off'"
  [[ "$PLAYERS" =~ ^[0-9]+$ && "$PLAYERS" -ge 1 ]] || die "PLAYERS must be a positive number"
  # Light: blue-lightblue deeppurple-amber indigo-pink deeporange-indigo.
  # Dark: bluegrey-lightgreen pink-bluegrey purple-green lime-green neon-fire.
  [[ "$(env_get JUICE_THEME)" =~ ^(blue-lightblue|deeppurple-amber|indigo-pink|deeporange-indigo|bluegrey-lightgreen|pink-bluegrey|purple-green|lime-green|neon-fire)$ ]] ||
    die "JUICE_THEME '$(env_get JUICE_THEME)' is not a Juice Shop theme"
  ADMIN="$(env_get TINYAUTH_ADMIN_USER)"
  # The organiser's name is also a hostname, a tinyauth app id (no "_") and a
  # compose service suffix, and must not shadow another host.
  [[ "$ADMIN" =~ ^[a-z][a-z0-9-]*$ ]] || die "TINYAUTH_ADMIN_USER must be lowercase letters, digits and '-'"
  [[ ! "$ADMIN" =~ ^(auth|ctf|juice|to-https|player[0-9]+)$ ]] || die "TINYAUTH_ADMIN_USER '$ADMIN' clashes with a hostname"
}

# Everyone who owns a Juice Shop: the organiser (for demos), then the players.
instances() {
  local i
  echo "$ADMIN"
  for ((i = 1; i <= PLAYERS; i++)); do echo "player$i"; done
}

gen_certs() {
  [[ -f "$CERT_DIR/server.crt" && -f "$CERT_DIR/server.key" && -f "$CERT_DIR/ca.crt" ]] && return 0
  info "Creating a local CA and a wildcard certificate for *.$DOMAIN"
  mkdir -p "$CERT_DIR"
  chmod 700 "$CERT_DIR"
  run_tool -e DOMAIN="$DOMAIN" -e CA_NAME="Pizza Hacking local CA ($DOMAIN)" "$TOOLS_IMAGE" sh -eu -c '
    cd "$(mktemp -d)"
    openssl req -x509 -newkey rsa:3072 -nodes -days 825 -sha256 \
      -keyout ca.key -out ca.crt -subj "/CN=$CA_NAME" \
      -addext "basicConstraints=critical,CA:TRUE,pathlen:0" \
      -addext "keyUsage=critical,keyCertSign,cRLSign" 2>/dev/null
    openssl req -newkey rsa:2048 -nodes -keyout server.key -out server.csr \
      -subj "/CN=$DOMAIN" 2>/dev/null
    printf "subjectAltName=DNS:%s,DNS:*.%s\nbasicConstraints=CA:FALSE\nkeyUsage=critical,digitalSignature,keyEncipherment\nextendedKeyUsage=serverAuth\n" \
      "$DOMAIN" "$DOMAIN" >ext.cnf
    openssl x509 -req -in server.csr -CA ca.crt -CAkey ca.key -CAcreateserial \
      -days 397 -sha256 -extfile ext.cnf -out server.crt 2>/dev/null
    tar -cf - ca.crt ca.key server.crt server.key
  ' | tar -C "$CERT_DIR" -xf -
  chmod 600 "$CERT_DIR"/*.key
}

# tinyauth users file: one "user:bcrypt" per line, hashed by tinyauth itself.
# Passwords go in on stdin so they never show up in the process list.
gen_tinyauth() {
  local i
  mkdir -p "$GEN_DIR/tinyauth"
  {
    printf '%s %s\n' "$(env_get TINYAUTH_ADMIN_USER)" "$(env_get TINYAUTH_ADMIN_PASSWORD)"
    for ((i = 1; i <= PLAYERS; i++)); do
      printf 'player%s %s\n' "$i" "$(env_get "PLAYER${i}_PASSWORD")"
    done
  } | run_tool --entrypoint sh "$TINYAUTH_IMAGE" -c '
    while read -r user pass; do
      tinyauth user create --username "$user" --password "$pass" 2>&1 \
        | sed "s/\x1b\[[0-9;]*m//g" | sed -n "s/^[[:space:]]*- \([^:]*:\$2.*\)$/\1/p"
    done
  ' >"$GEN_DIR/tinyauth/users.tmp"
  [[ "$(wc -l <"$GEN_DIR/tinyauth/users.tmp")" -eq $((PLAYERS + 1)) ]] || die "tinyauth user hashing failed"
  mv "$GEN_DIR/tinyauth/users.tmp" "$GEN_DIR/tinyauth/users"

  local admin="$ADMIN" all_players="" apps="" owner allow
  for ((i = 1; i <= PLAYERS; i++)); do all_players+="player$i,"; done
  for owner in $(instances); do
    # Each instance admits its owner and the organiser.
    allow="$owner"
    [[ "$owner" == "$admin" ]] || allow+=",$admin"
    # App ids are a single token: tinyauth splits config keys on "_".
    apps+="  $owner:
    config:
      domain: $owner.$DOMAIN
    users:
      allow: $allow
"
  done
  cat >"$GEN_DIR/tinyauth/config.yml" <<EOF
# Generated by pizza.sh — edit pizza.sh, not this file.
appUrl: https://auth.$DOMAIN$PORT_SUFFIX
# No docker socket is mounted; ACLs come only from this file.
labelProvider: none
analytics:
  enabled: false
resources:
  enabled: false
auth:
  usersFile: /config/users
  secureCookie: true
  sessionExpiry: 43200
  loginMaxRetries: 5
  loginTimeout: 120
  # Hosts without a rule below are denied, never open to every user.
  acls:
    policy: deny
ui:
  title: $(env_get CTF_NAME)
  forgotPasswordMessage: Ask the organiser for your login.
apps:
$apps  ctf:
    config:
      domain: ctf.$DOMAIN
    users:
      allow: $all_players$admin
  juice:
    config:
      domain: juice.$DOMAIN
    users:
      allow: $all_players$admin
EOF
}

# One router per host on the TLS entrypoint, plus a twin on the plain-HTTP
# "proxy" entrypoint for a reverse proxy that terminates TLS in front of us.
router() {
  local name="$1" host="$2" service="$3" mw="$4"
  printf '    %s:\n      rule: Host(`%s`)\n      entryPoints: [websecure]\n' "$name" "$host"
  [[ -n "$mw" ]] && printf '      middlewares: [%s]\n' "$mw"
  printf '      service: %s\n      tls: {}\n' "$service"
  printf '    %s-proxied:\n      rule: Host(`%s`)\n      entryPoints: [proxy]\n' "$name" "$host"
  printf '      middlewares: [proxied-https%s]\n' "${mw:+, $mw-proxied}"
  printf '      service: %s\n' "$service"
}

gen_traefik() {
  local owner routers services=""
  mkdir -p "$GEN_DIR/traefik"
  routers="$(router auth "auth.$DOMAIN" tinyauth "")
$(router ctf "ctf.$DOMAIN" ctfd sso)
$(router juice "juice.$DOMAIN" landing sso)"
  for owner in $(instances); do
    routers+="
$(router "$owner" "$owner.$DOMAIN" "$owner" sso)"
    services+="
    $owner:
      loadBalancer:
        servers:
          - url: http://juice-$owner:3000"
  done
  cat >"$GEN_DIR/traefik/dynamic.yml" <<EOF
# Generated by pizza.sh — edit pizza.sh, not this file.
http:
  routers:
    to-https:
      rule: PathPrefix(\`/\`)
      entryPoints: [web]
      middlewares: [to-https]
      service: noop@internal
$routers

  middlewares:
    sso:
      forwardAuth:
        address: http://tinyauth:3000/api/auth/traefik
        authResponseHeaders: [Remote-User, Remote-Name, Remote-Email]
        # Never pass client-supplied X-Forwarded-* to tinyauth.
        trustForwardHeader: false
        maxResponseBodySize: 1048576
    # Same gate for the proxy entrypoint. Trusting X-Forwarded-* is safe here:
    # the entrypoint drops any the client sent (no trusted IPs configured) and
    # proxied-https sets Proto/Port, so tinyauth builds https:// redirects.
    sso-proxied:
      forwardAuth:
        address: http://tinyauth:3000/api/auth/traefik
        authResponseHeaders: [Remote-User, Remote-Name, Remote-Email]
        trustForwardHeader: true
        maxResponseBodySize: 1048576
    # The proxy entrypoint is only reached through a TLS-terminating proxy,
    # so tell the apps the request was HTTPS on the public port.
    proxied-https:
      headers:
        customRequestHeaders:
          X-Forwarded-Proto: https
          X-Forwarded-Port: "$PUBLIC_PORT"
    to-https:
      redirectRegex:
        regex: ^http://([^/:]+)(:[0-9]+)?(.*)
        replacement: https://\${1}$PORT_SUFFIX\${3}

  services:
    tinyauth:
      loadBalancer:
        servers:
          - url: http://tinyauth:3000
    ctfd:
      loadBalancer:
        servers:
          - url: http://ctfd:8000
    landing:
      loadBalancer:
        servers:
          - url: http://landing:80$services

tls:
  certificates:
    - certFile: /certs/server.crt
      keyFile: /certs/server.key
  stores:
    default:
      defaultCertificate:
        certFile: /certs/server.crt
        keyFile: /certs/server.key
EOF
}

gen_players_compose() {
  local owner juice="" nets="" traefik_nets="" aliases
  aliases="            - auth.$DOMAIN
            - ctf.$DOMAIN
            - juice.$DOMAIN"
  for owner in $(instances); do
    aliases+="
            - $owner.$DOMAIN"
    traefik_nets+="
      $owner: {}"
    nets+="
  $owner:
    internal: true"
    juice+="
  juice-$owner:
    image: $JUICE_IMAGE
    restart: unless-stopped
    pids_limit: 1024
    security_opt: [\"no-new-privileges:true\"]
    environment:
      NODE_ENV: ctf
      CTF_KEY: \${CTF_KEY}
      NODE_CONFIG: '{\"application\":{\"theme\":\"\${JUICE_THEME}\"}}'
    networks: [$owner]"
  done
  local ports="
      - \"$HTTPS_PORT:443\""
  [[ "$HTTP_PORT" == "off" ]] || ports+="
      - \"$HTTP_PORT:80\""
  cat >"$GEN_DIR/docker-compose.players.yml" <<EOF
# Generated by pizza.sh — edit pizza.sh, not this file.
# One Juice Shop per player plus one for the organiser ($ADMIN). Each sits on
# its own internal network: no internet, and no route to CTFd, tinyauth or
# another instance (think SSRF). Only Traefik
# joins them all. The aliases let in-stack clients (the tests) reach every
# public hostname through Traefik.
services:
  traefik:
    ports:$ports
    networks:
      edge:
        aliases:
$aliases$traefik_nets
$juice

  # Imports challenges from the organiser's instance, which always exists.
  ctfd-bootstrap:
    networks: [edge, $ADMIN]

networks:$nets
EOF
}

# Hints are not served by Juice Shop in CTF mode (players buy them in CTFd),
# so read them from the challenge definitions inside the same pinned image.
export_meta() {
  [[ -s "$GEN_DIR/challenges-meta.json" ]] && return 0
  info "Exporting challenge hints from $JUICE_IMAGE"
  run_tool --entrypoint /nodejs/bin/node -w /juice-shop "$JUICE_IMAGE" -e '
    const yaml = require("js-yaml"), fs = require("fs");
    const all = yaml.load(fs.readFileSync("data/static/challenges.yml", "utf8"));
    process.stdout.write(JSON.stringify(all.map(c => ({ key: c.key, name: c.name, hints: c.hints || [] }))));
  ' >"$GEN_DIR/challenges-meta.json.tmp"
  mv "$GEN_DIR/challenges-meta.json.tmp" "$GEN_DIR/challenges-meta.json"
}

# tinyauth reads its users and ACLs only at startup, and `compose up` does not
# recreate it when just the mounted files change. Recreate it whenever they
# do (Traefik's file provider reloads by itself). The users file is re-hashed
# with fresh salts on every run, so fingerprint its inputs instead: the
# config plus every user's password. Kept in the private generated/ dir.
tinyauth_fingerprint() {
  {
    cat "$GEN_DIR/tinyauth/config.yml"
    printf '%s %s\n' "$ADMIN" "$(env_get TINYAUTH_ADMIN_PASSWORD)"
    local i
    for ((i = 1; i <= PLAYERS; i++)); do
      printf 'player%s %s\n' "$i" "$(env_get "PLAYER${i}_PASSWORD")"
    done
  } | cksum
}

reload_tinyauth() {
  local now applied="$GEN_DIR/.tinyauth-applied"
  now="$(tinyauth_fingerprint)"
  [[ -f "$applied" && "$(cat "$applied")" == "$now" ]] && return 0
  info "Reloading tinyauth with the current users and ACLs"
  compose up -d --no-deps --force-recreate tinyauth
  printf '%s\n' "$now" >"$applied"
}

generate() {
  mkdir -p "$GEN_DIR"
  chmod 700 "$GEN_DIR"
  gen_certs
  gen_tinyauth
  gen_traefik
  gen_players_compose
  export_meta
}

print_creds() {
  [[ -f "$ENV_FILE" ]] || die "no .env yet — run ./pizza.sh up first"
  load_env >/dev/null
  local base="https://%s.$DOMAIN$PORT_SUFFIX" i
  echo
  echo "================ $(env_get CTF_NAME) ================"
  printf "Scoreboard (CTFd):   $base/\n" ctf
  printf "Your Juice Shop:     $base/   (sends everyone to their own)\n" juice
  echo
  echo "IdP login (tinyauth, needed for every page):"
  printf "  %-10s %-22s $base/   (organiser: own demo shop, can open every instance)\n" "$ADMIN" "$(env_get TINYAUTH_ADMIN_PASSWORD)" "$ADMIN"
  for ((i = 1; i <= PLAYERS; i++)); do
    printf "  %-10s %-22s $base/\n" "player$i" "$(env_get "PLAYER${i}_PASSWORD")" "player$i"
  done
  echo
  echo "CTFd administrator (separate account, log in at the scoreboard):"
  printf "  %-10s %s\n" "$(env_get CTFD_ADMIN_USER)" "$(env_get CTFD_ADMIN_PASSWORD)"
  echo
  echo "Players register their own CTFd account to collect points."
  echo "TLS is self-signed: import $CERT_DIR/ca.crt into your browser"
  echo "(or click through the warning once per hostname)."
  echo "All of this is stored in $ENV_FILE"
  echo "=================================================="
}

cmd_up() {
  local players=""
  while [[ $# -gt 0 ]]; do
    case "$1" in
      --players|-n) players="${2:-}"; shift 2 ;;
      --players=*) players="${1#*=}"; shift ;;
      *) die "unknown option: $1" ;;
    esac
  done
  check_prereqs
  init_env
  # Without --players, keep the current count.
  [[ -n "$players" ]] || players="$(env_get PLAYERS)"
  [[ "$players" =~ ^[0-9]+$ && "$players" -ge 1 ]] || die "--players needs a positive number"
  ensure_players "$players"
  load_env
  generate
  info "Starting $PLAYERS player instance(s) + 1 for $ADMIN on https://*.$DOMAIN$PORT_SUFFIX"
  # --remove-orphans drops instances of players removed by a lower --players.
  # It is scoped to this compose project (-p) only.
  compose up -d --remove-orphans
  reload_tinyauth
  info "Setting up CTFd and importing challenges (first run takes a minute)"
  compose --profile tools run --rm ctfd-bootstrap
  if [[ "$FIRST_RUN" -eq 1 ]]; then
    print_creds
  else
    info "Done. ./pizza.sh creds prints the logins."
  fi
}

cmd_down() {
  check_prereqs
  [[ -f "$ENV_FILE" ]] || die "nothing to stop: no .env in $STATE_DIR"
  if [[ "${1:-}" == "--wipe" ]]; then
    compose --profile tools --profile test down --volumes --remove-orphans
    rm -rf "$GEN_DIR" "$CERT_DIR" "$ENV_FILE"
    info "Stack, CTFd data, credentials and certificates deleted"
  else
    compose --profile tools --profile test down --remove-orphans
    info "Stopped. CTFd data is kept; Juice Shop progress is not."
  fi
}

cmd_reset_juice() {
  check_prereqs
  load_env
  local owner svcs=()
  for owner in $(instances); do svcs+=("juice-$owner"); done
  compose up -d --force-recreate "${svcs[@]}"
}

# End-to-end tests in a throwaway stack: own project, state dir and ports.
cmd_test() {
  check_prereqs
  export PIZZA_PROJECT="${PIZZA_TEST_PROJECT:-pizza-hacking-test}"
  export PIZZA_STATE_DIR="${PIZZA_TEST_STATE_DIR:-$REPO_DIR/.test-state}"
  export HTTP_PORT="${TEST_HTTP_PORT:-18080}" HTTPS_PORT="${TEST_HTTPS_PORT:-18443}"
  export DOMAIN="${TEST_DOMAIN:-pizza.test}"
  unset PUBLIC_PORT PIZZA_COMPOSE_OVERRIDE
  local self="$REPO_DIR/pizza.sh" rc=0
  [[ -e "$PIZZA_STATE_DIR/.env" ]] && die "$PIZZA_STATE_DIR already exists — remove it or run ./pizza.sh test-clean"
  # shellcheck disable=SC2064  # expand now: the locals are gone when it fires
  trap "'$self' down --wipe >/dev/null 2>&1 || true; rm -rf '$PIZZA_STATE_DIR'" EXIT

  info "[test] stage 1: one player"
  "$self" up --players 1 >/dev/null
  STATE_DIR="$PIZZA_STATE_DIR" ENV_FILE="$PIZZA_STATE_DIR/.env" GEN_DIR="$PIZZA_STATE_DIR/generated" PROJECT="$PIZZA_PROJECT"
  cp "$ENV_FILE" "$PIZZA_STATE_DIR/env.stage1"
  compose --profile test run --rm tests -m "stage1" "$@" || rc=$?

  info "[test] stage 2: stop, start again, then add a second player to the running stack"
  "$self" down >/dev/null
  "$self" up --players 1 >/dev/null
  # Adding a player live is the path where tinyauth must reload its config.
  "$self" up --players 2 >/dev/null
  compose --profile test run --rm -e PIZZA_STAGE1_ENV=/state/env.stage1 tests -m "stage2" "$@" || rc=$?
  return "$rc"
}

cmd_test_clean() {
  export PIZZA_PROJECT="${PIZZA_TEST_PROJECT:-pizza-hacking-test}"
  export PIZZA_STATE_DIR="${PIZZA_TEST_STATE_DIR:-$REPO_DIR/.test-state}"
  "$REPO_DIR/pizza.sh" down --wipe || true
  rm -rf "$PIZZA_STATE_DIR"
}

main() {
  local cmd="${1:-help}"
  shift || true
  case "$cmd" in
    up) cmd_up "$@" ;;
    down) cmd_down "$@" ;;
    creds) print_creds ;;
    status) check_prereqs; compose ps ;;
    logs) check_prereqs; compose logs -f "$@" ;;
    reset-juice) cmd_reset_juice ;;
    test) cmd_test "$@" ;;
    test-clean) cmd_test_clean ;;
    help|-h|--help) sed -n '2,16p' "$0" | sed 's/^# \{0,1\}//' ;;
    *) die "unknown command '$cmd' (try ./pizza.sh help)" ;;
  esac
}

main "$@"
